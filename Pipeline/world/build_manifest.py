# Drowned City: Pipeline/world/assets.json: each delivered file, what made it, its seed and licence, each piece's triangles and collision, and which culture's kit it belongs to (W13a).
import glob, json, os
HERE = os.path.dirname(os.path.abspath(__file__))
A = os.environ.get('WORLD_ASSETS') or os.path.abspath(os.path.join(HERE, '..', '..', 'web', 'assets'))
P = json.load(open(os.path.join(HERE, 'out', 'pieces.json')))
fp = os.path.join(HERE, 'out', 'col_fit.json')
FIT = json.load(open(fp)) if os.path.exists(fp) else {}
LIC = 'Original work, generated by this repository\'s code on 31 Oct 2026. No third-party meshes, textures or scans.'
MAP = 'Pipeline/world/build_world.py'
GLB = 'Pipeline/world/build_assets.py, gen_*.py; gltfpack (MIT)'
TEX = 'Pipeline/world/build_tex.py'
files = [('world.json', MAP, 1931), ('height.bin', MAP, 1931), ('biome.bin', MAP, 1931), ('biome2.bin', MAP, 1931), ('height_z.bin', MAP, 1931), ('biome_z.bin', MAP, 1931), ('biome2_z.bin', MAP, 1931),
         ('props.glb', GLB, 'one per piece'), ('creatures.glb', GLB, 'one per piece'),
         ('tex/caustics.png', TEX, 1931), ('tex/sand_n.png', TEX, 1931), ('tex/rock_n.png', TEX, 1931), ('tex/sand_n.webp', TEX + '; cwebp', 1931), ('tex/rock_n.webp', TEX + '; cwebp', 1931)]
files += [(os.path.basename(f), GLB, 'one per piece') for f in sorted(glob.glob(os.path.join(A, 'props_*.glb')))]
KITS = {'marble': ['column', 'column_broken', 'column_fallen', 'wall_bay', 'wall_broken', 'arch', 'stair', 'temple_front', 'arena_bay', 'arena_portal'],
        'gilded': ['dome_hall', 'tower', 'wall_windows', 'bridge_span'],
        'cliff': ['tower_cold', 'wall_windows_cold', 'stair_steep'],
        'ice': ['ice_wall', 'ice_tower', 'ice_gate'],
        'timber village': ['cottage_a', 'cottage_b', 'stone_wall', 'quay', 'pier', 'pier_house', 'lighthouse']}
out = {'note': LIC, 'kits': KITS, 'files': [], 'pieces': {}}
total = 0
for f, gen, seed in files:
    q = os.path.join(A, f)
    if not os.path.exists(q):
        continue
    size = os.path.getsize(q)
    total += size
    out['files'].append({'file': 'web/assets/' + f, 'bytes': size, 'generator': gen, 'seed': seed, 'licence': LIC})
out['total_bytes'] = total
for k, v in sorted(P.items()):
    e = {'tris': v['tris'], 'size_m': v['size'], 'colliders': len(FIT[k]['col']) if k in FIT else len(v.get('col', []))}
    if k in FIT:
        e.update({'a1v_p95': FIT[k]['p95'], 'a2_bad': FIT[k]['bad'], 'openings': len(FIT[k].get('openings') or [])})
    out['pieces'][k] = e
json.dump(out, open(os.path.join(HERE, 'assets.json'), 'w'), indent=1)
print('assets.json', len(out['pieces']), 'pieces', total, 'bytes')
